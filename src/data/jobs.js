export function getJobById(id) {
  return JOBS.find((j) => j.id === id);
}

export function getSectorById(id) {
  return SECTORS.find((s) => s.id === id);
}

export function sectorLabel(id) {
  return (getSectorById(id) || {}).name || id;
}

const round1k = (n) => Math.round(n / 1000) * 1000;

/** Split a job's min–max range into entry / mid / senior thirds. */
export function jobBands(job) {
  const span = job.max - job.min;
  return {
    entry: [round1k(job.min), round1k(job.min + span / 3)],
    mid: [round1k(job.min + span / 3), round1k(job.min + (2 * span) / 3)],
    senior: [round1k(job.min + (2 * span) / 3), round1k(job.max)],
  };
}

export function fmtNPR(n) {
  return Number(n).toLocaleString('en-IN');
}

export function inr(n) {
  return 'Rs ' + fmtNPR(Math.round(n));
}
