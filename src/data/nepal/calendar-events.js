export const CALENDAR_EVENTS = EVENTS;

export function resolveEvent(eventDef, bsYear) {
  const rule = eventDef.rule;
  if (rule.kind === 'bs') {
    const ad = bsToAd(bsYear, rule.month, rule.day);
    return ad && { event: eventDef, bs: { year: bsYear, month: rule.month, day: rule.day }, ad };
  }
  if (rule.kind === 'ad') {
    const newYearAd = bsToAd(bsYear, 1, 1);
    if (!newYearAd) return null;
    for (let cand = newYearAd.year; cand <= newYearAd.year + 1; cand++) {
      const ad = { year: cand, month: rule.month, day: rule.day };
      const back = adToBs(ad.year, ad.month, ad.day);
      if (back && back.year === bsYear) return { event: eventDef, bs: back, ad };
    }
    return null;
  }
  return null;
}

export function getEventsForBsYear(bsYear) {
  const resolved = [];
  for (const def of CALENDAR_EVENTS) {
    const r = resolveEvent(def, bsYear);
    if (r) resolved.push(r);
  }
  resolved.sort((a, b) => compareDates(a.bs, b.bs));
  return resolved;
}

export function getEventsForBsMonth(bsYear, bsMonth) {
  return getEventsForBsYear(bsYear).filter((e) => e.bs.month === bsMonth);
}

export function getEventStatus(resolvedEvent, todayBs) {
  const cmp = compareDates(resolvedEvent.bs, todayBs);
  if (cmp < 0) return 'past';
  if (cmp === 0) return 'today';
  return 'upcoming';
}

export function getUpcomingEvents(todayBs, { limit = 8 } = {}) {
  const out = [];
  let year = todayBs.year;
  while (out.length < limit && year <= BS_MAX_YEAR) {
    for (const r of getEventsForBsYear(year)) {
      if (compareDates(r.bs, todayBs) >= 0) {
        out.push({ ...r, status: compareDates(r.bs, todayBs) === 0 ? 'today' : 'upcoming' });
        if (out.length >= limit) break;
      }
    }
    year += 1;
  }
  return out.slice(0, limit);
}

export function getRecentPastEvents(todayBs, { limit = 6 } = {}) {
  const out = [];
  let year = todayBs.year;
  while (out.length < limit && year >= BS_MIN_YEAR) {
    const yearEvents = getEventsForBsYear(year);
    for (let i = yearEvents.length - 1; i >= 0; i--) {
      if (compareDates(yearEvents[i].bs, todayBs) < 0) {
        out.push({ ...yearEvents[i], status: 'past' });
        if (out.length >= limit) break;
      }
    }
    year -= 1;
  }
  return out.slice(0, limit);
}
