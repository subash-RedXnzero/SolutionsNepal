/**
 * Get the tithi name for a given BS date.
 * @param {number} bsYear
 * @param {number} bsMonth
 * @param {number} bsDay
 * @returns {string|null} Tithi name in Nepali, or null if not available.
 */
export function getTithi(bsYear, bsMonth, bsDay) {
  const key = `${bsYear}-${bsMonth}`;
  const monthData = TITHI_DATA[key];
  if (!monthData) return null;
  return monthData[bsDay] || null;
}

/**
 * Check if a tithi is a major/significant one.
 * @param {string} tithi
 * @returns {boolean}
 */
export function isMajorTithi(tithi) {
  return MAJOR_TITHIS.has(tithi);
}
