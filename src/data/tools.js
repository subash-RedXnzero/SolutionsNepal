export function getPopularTools(limit = 8) {
  return tools.filter(t => t.popular).slice(0, limit);
}

export function getToolsByCategory(categoryId) {
  return tools.filter(t => t.category === categoryId);
}

export function getToolById(id) {
  return tools.find(t => t.id === id);
}

export function getRelatedTools(currentId) {
  const current = getToolById(currentId);
  if (!current) return [];
  return tools.filter(t => t.id !== currentId && t.category === current.category).slice(0, 4);
}
