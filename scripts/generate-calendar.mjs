function slugify(name) {
  return name.toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 64);
}

function categorize(name) {
  const n = name.toLowerCase();
  // International days
  if (n.includes('vishwa') || n.includes('antarastriya') || n.includes('international') || n.includes('world ')) return 'international';
  // National observances
  if (n.includes('divas') || n.includes('day') || n.includes('diwas')) return 'observance';
  // Festivals
  if (n.includes('jatra') || n.includes('festival') || n.includes('parva') || n.includes('chhath') || n.includes('teej') || n.includes('lhosar') || n.includes('holi') || n.includes('tihar') || n.includes('dashain') || n.includes('bandhan') || n.includes('mela') || n.includes('jatra')) return 'festival';
  // Religious
  if (n.includes('vrat') || n.includes('ekadashi') || n.includes('pradosh') || n.includes('puja') || n.includes('sankranti') || n.includes('purnima') || n.includes('aunsi') || n.includes('jayanti') || n.includes('sraddha') || n.includes('snan')) return 'religious';
  return 'observance';
}

function getScope(name) {
  const n = name.toLowerCase();
  if (n.includes('kathmandu') || n.includes('gai jatra') || n.includes('indra jatra') || n.includes('ghode jatra') || n.includes('bhoto') || n.includes('biska') || n.includes('machhindranath')) return 'kathmandu-valley';
  if (n.includes("women") || n.includes("teej") || n.includes("mahila")) return 'women';
  return 'national';
}

